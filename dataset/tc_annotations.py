def apply(task):
    """Merge ANNOTATIONS into ``task`` in place; raise on any mismatch."""
    tid = task["id"]
    per_case = ANNOTATIONS.get(tid)
    if per_case is None:
        raise ValueError("%s: no test-case annotations" % tid)
    spec_ids = {s["id"] for s in task.get("ltl_specs", [])}
    for tc in task["test_cases"]:
        ann = per_case.get(tc["id"])
        if ann is None:
            raise ValueError("%s %s: no annotation" % (tid, tc["id"]))
        n_steps = len(tc["steps"])
        if len(ann["steps"]) != n_steps:
            raise ValueError("%s %s: %d purposes for %d steps"
                             % (tid, tc["id"], len(ann["steps"]), n_steps))
        bad = [s for s in ann["specRefs"] if s not in spec_ids]
        if bad:
            raise ValueError("%s %s: unknown spec %s"
                             % (tid, tc["id"], bad))
        tc["initialState"] = ann["initialState"]
        tc["coverage"] = list(ann["coverage"])
        tc["specRefs"] = list(ann["specRefs"])
        for st, purpose in zip(tc["steps"], ann["steps"]):
            st["purpose"] = purpose
    extra = set(per_case) - {c["id"] for c in task["test_cases"]}
    if extra:
        raise ValueError("%s: annotations for unknown cases %s"
                         % (tid, sorted(extra)))
    return task


def _write_example():
    """Rewrite dataset/tasks/example_motor.json in place with annotations.

    The schema example is not produced by the build scripts, so it is updated
    by this helper:  python dataset/tc_annotations.py --write-example
    """
    import json
    import os
    here = os.path.dirname(os.path.abspath(__file__))
    path = os.path.join(here, "tasks", "example_motor.json")
    with open(path, encoding="utf-8") as f:
        task = json.load(f)
    apply(task)
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        json.dump(task, f, ensure_ascii=False, indent=2)
    print("wrote", path)


if __name__ == "__main__":
    import sys
    if "--write-example" in sys.argv:
        _write_example()
    else:
        print(__doc__)
