"""Per-test-case annotations required by the assignment's test-case template.

The structured test cases in ``TASKS`` (build_public.py / build_self.py) only
carry the machine-executable part: inputs, expectations and repeat counts.
The template additionally asks for

* ``initialState``  -- state before the case starts (template: 初始状态)
* ``coverage``      -- what the case checks (template: 覆盖内容)
* ``specRefs``      -- LTL specs this case gives evidence for (traceability)
* ``steps[].purpose`` -- per-step check description (template: 检查内容)

This module holds that prose. Both build scripts call ``apply(task)`` right
before dumping the JSON, so the annotations end up inside
``dataset/tasks/*.json`` and are picked up by ``dataset/render_cases.py``
(which renders ``report/测试用例.md``) and enforced by ``dataset/validate.py``.

Timing convention: a step's ``expect`` is evaluated **after** that scan. Where
the reference implementation is a ``CASE`` state machine, a transition taken in
scan k shows up on the outputs in scan k+1; the step purposes say so explicitly
("下一拍生效") because hand-written tests encode that timing.

Only outputs listed in ``expect`` are compared -- see schema.md.
"""


def _c(initial_state, coverage, spec_refs, steps):
    return {"initialState": initial_state, "coverage": coverage,
            "specRefs": spec_refs, "steps": steps}


